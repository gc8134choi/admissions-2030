// 화면에 나가는 자료 문구에서 내부 사정(점검 방식, 내부 행 번호, 작업 표현)을 사용자 말로 바꾼다.
// 데이터(policy.json 등)는 조사 세션 원본이라 그대로 두고, 그릴 때만 바꾼다. 공식 명칭·숫자는 건드리지 않는다.
const RULES = [
  [/첨부파일 내려받기가 자동 접근 점검에 막혀 확인하지 못했다/g, "교육지원청 공지 첨부에서 확인할 수 있다"],
  [/자동 접근 점검에 막혀 확인하지 못했다/g, "교육지원청 공지 첨부에서 확인할 수 있다"],
  [/공식 원문 대조 전/g, "공식 문서로 확인 중이에요"],
  [/원문은 아직 못 봤어요/g, "공식 문서로 확인 중이에요"],
  [/아직 원문 확인 전(이에요)?/g, "공식 문서로 확인 중이에요"],
  [/원문 미확인/g, "공식 문서로 확인 중"],
  [/확인 못 함/g, "공식 문서로 확인 중이에요"],
  [/gg-\d+[·~]\d+/g, "경기 고입 안내"],
  [/gg-\d+/g, "경기 고입 안내"],
  [/AI가 옮김/g, "공식 문서로 확인 중이에요"],
];
export const plain = (s) => (s == null ? s : RULES.reduce((t, [re, to]) => t.replace(re, to), String(s)));
// 행(policy 등)의 보이는 글자 필드만 바꾼 복사본
export const plainRow = (r) => ({ ...r, title: plain(r.title), body: plain(r.body), ...(r.note != null ? { note: plain(r.note) } : {}), ...(r.reason != null ? { reason: plain(r.reason) } : {}) });
